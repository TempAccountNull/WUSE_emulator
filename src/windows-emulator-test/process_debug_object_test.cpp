    TEST_P(ProcessDebugObjectTest, MatchesNativeProtectedAliasAndRangeMatrix)
    {
        ASSERT_NE(emu.vcpu(0).active_thread, nullptr);
        const auto own_event = emu.process.events.store(event{});
        for (size_t index = 0; index < native_page_cases.size(); ++index)
        {
            const auto& observed = native_page_cases[index];
            SCOPED_TRACE(testing::Message() << "native page row=" << index << " length=" << observed.length
                                            << " target=" << static_cast<int>(observed.target) << " alias=" << observed.alias_offset);
            const auto output_base = memory + 0x10000 + index * 0x20000;
            const auto returned_base = output_base + 0x10000;
            ASSERT_TRUE(prepare_native_page(emu, output_base, observed.output_mode, observed.output_before));
            if (observed.alias_offset < 0)
            {
                ASSERT_TRUE(prepare_native_page(emu, returned_base, observed.return_mode, observed.return_before));
            }
            uint64_t output = output_base + 256 + observed.output_shift;
            uint64_t returned = observed.alias_offset < 0 ? returned_base + 256 + observed.return_shift
                                                          : output + static_cast<uint32_t>(observed.alias_offset);
            if (observed.output_null)
            {
                output = 0;
            }
            if (observed.return_null)
            {
                returned = 0;
            }
            if (observed.raw_output != 0)
            {
                output = observed.raw_output;
            }
            if (observed.raw_return != 0)
            {
                returned = observed.raw_return;
            }
            const auto process = select_native_page_target(observed.target, own_event);
            EXPECT_EQ(query(process, ProcessDebugObjectHandle, output, observed.length, returned), observed.status);
            const auto check_page = [&](const uint64_t base, const page_mode mode, const bool expected_guard,
                                        const std::string_view expected_after) {
                const auto region = emu.memory.get_region_info(base);
                EXPECT_EQ(region.is_reserved, mode != page_mode::released);
                EXPECT_EQ(region.is_committed, mode != page_mode::reserved_uncommitted && mode != page_mode::released);
                EXPECT_EQ(region.permissions.is_guarded(), expected_guard);
                if (!expected_after.empty())
                {
                    ASSERT_TRUE(region.is_committed);
                    ASSERT_TRUE(emu.memory.protect_memory(base, 0x1000, memory_permission::read_write));
                    EXPECT_EQ((emu.memory.read_memory<std::array<uint8_t, 0x1000>>(base)), native_page_bytes(expected_after));
                }
            };
            check_page(output_base, observed.output_mode, observed.output_guard, observed.output_after);
            if (observed.alias_offset < 0)
            {
                check_page(returned_base, observed.return_mode, observed.return_guard, observed.return_after);
            }
        }
    }

